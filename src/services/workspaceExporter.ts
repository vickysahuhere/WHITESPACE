/**
 * Workspace Exporter & Local Agent Bridge Engine
 * Generates unified context.md packages, complete JSON backup/restore manifests,
 * and the standalone wc_bridge.py Python local tool bridge for Google Antigravity & Cursor.
 */

import { Space, Member, Document, Task, BrowserTab, ChatHistoryStore } from '../types';

export interface ExportParams {
  space: Space;
  member: Member;
  documents: Document[];
  tasks: Task[];
  sharedTabs: BrowserTab[];
}

export interface FullStateParams {
  spaces: Space[];
  members: Member[];
  documents: Document[];
  tasks: Task[];
  tabs: BrowserTab[];
  chatStore?: ChatHistoryStore;
}

export interface BackupPayload {
  version: string;
  exportedAt: string;
  source: string;
  spaces: Space[];
  members: Member[];
  documents: Document[];
  tasks: Task[];
  tabs: BrowserTab[];
  chatStore?: ChatHistoryStore;
}

/**
 * Compiles a structured, zero-ambiguity context.md combining
 * space profile, SOUL.MD, full document texts, Kanban tasks, and shared tabs.
 */
export function generateContextMd(params: ExportParams): string {
  const { space, member, documents, tasks, sharedTabs } = params;
  const now = new Date().toISOString();

  const spaceDocs = documents.filter(d => d.spaceId === space.id);
  const spaceTasks = tasks.filter(t => t.spaceId === space.id);

  let md = `# WHITE COLLARS // AUTONOMOUS WORKSPACE OS: SPACE CONTEXT\n\n`;
  md += `> EXPORT TIMESTAMP: ${now}\n`;
  md += `> RUNTIME: WHITE COLLARS OS // MONOCHROME DESKTOP & WEB DUAL-TARGET\n\n`;

  md += `## 1. SPACE METADATA\n\n`;
  md += `- **Space Name**: ${space.name}\n`;
  md += `- **Slug**: ${space.slug}\n`;
  md += `- **Badge**: [${space.badge}]\n`;
  md += `- **Description**: ${space.description || 'Primary autonomous team space'}\n`;
  md += `- **Created**: ${space.createdAt}\n`;
  md += `- **Updated**: ${space.updatedAt}\n\n`;

  md += `## 2. ACTIVE WHITER (MEMBER PROFILE)\n\n`;
  md += `- **Member**: ${member.name} [${member.badge}]\n`;
  md += `- **Role**: ${member.role}\n`;
  md += `- **Hardware Target**: ${member.hardware}\n`;
  md += `- **Operational Directives**:\n\n${member.instructions || 'Standard engineering protocol'}\n\n`;

  md += `## 3. PERSISTENT SPACE SYSTEM PROMPT (SOUL.MD)\n\n`;
  md += `\`\`\`markdown\n${space.soulMd || '// No SOUL.MD configured'}\n\`\`\`\n\n`;

  md += `## 4. KANBAN ENGINEERING TASKS (${spaceTasks.length} ITEMS)\n\n`;
  const queued = spaceTasks.filter(t => t.column === 'queued');
  const active = spaceTasks.filter(t => t.column === 'active');
  const shipped = spaceTasks.filter(t => t.column === 'shipped');

  md += `### 01 // QUEUED SPECS (${queued.length})\n\n`;
  if (queued.length === 0) {
    md += `_No queued tasks._\n\n`;
  } else {
    queued.forEach((t, i) => {
      md += `#### [${t.priority}] ${t.title}\n`;
      md += `- Task ID: \`${t.id}\`\n`;
      md += `- Spec: ${t.spec}\n\n`;
    });
  }

  md += `### 02 // ACTIVE AGENT LOOP (${active.length})\n\n`;
  if (active.length === 0) {
    md += `_No active tasks in loop._\n\n`;
  } else {
    active.forEach((t, i) => {
      md += `#### [${t.priority}] ${t.title}\n`;
      md += `- Task ID: \`${t.id}\`\n`;
      md += `- Spec: ${t.spec}\n\n`;
    });
  }

  md += `### 03 // VERIFIED & SHIPPED (${shipped.length})\n\n`;
  if (shipped.length === 0) {
    md += `_No shipped tasks yet._\n\n`;
  } else {
    shipped.forEach((t, i) => {
      md += `#### [${t.priority}] ${t.title}\n`;
      md += `- Task ID: \`${t.id}\`\n`;
      md += `- Spec: ${t.spec}\n\n`;
    });
  }

  md += `## 5. TEAM SHARED BROWSER TABS & EXTERNAL SPECS (${sharedTabs.length} TABS)\n\n`;
  if (sharedTabs.length === 0) {
    md += `_No tabs currently marked TAB: SHARED WITH TEAM._\n\n`;
  } else {
    sharedTabs.forEach((tab) => {
      md += `- **[${tab.type.toUpperCase()}]** [${tab.title}](${tab.url}) (ID: \`${tab.id}\`)\n`;
    });
    md += `\n`;
  }

  md += `## 6. KNOWLEDGE BASE DOCUMENTS (${spaceDocs.length} FILES)\n\n`;
  if (spaceDocs.length === 0) {
    md += `_No documents stored in this space._\n\n`;
  } else {
    spaceDocs.forEach((doc, idx) => {
      md += `### DOCUMENT ${idx + 1}: ${doc.title} (.${doc.format})\n`;
      md += `- **ID**: \`${doc.id}\`\n`;
      md += `- **Format**: \`${doc.format}\`\n`;
      md += `- **Updated**: ${doc.updatedAt}\n`;
      md += `- **Content**:\n\n`;
      md += `\`\`\`${doc.format}\n${doc.content}\n\`\`\`\n\n`;
    });
  }

  md += `---\n`;
  md += `END OF WHITE COLLARS CONTEXT PACKAGE // GENERATED BY WHITE COLLARS OS\n`;

  return md;
}

/**
 * Serializes the full application state to a single validated JSON string.
 */
export function generateFullJsonBackup(params: FullStateParams): string {
  const payload: BackupPayload = {
    version: '1.0.0-whitespacerelease',
    exportedAt: new Date().toISOString(),
    source: 'White Collars (WHITESPACE) // Autonomous Workspace OS',
    spaces: params.spaces,
    members: params.members,
    documents: params.documents,
    tasks: params.tasks,
    tabs: params.tabs,
    chatStore: params.chatStore
  };

  return JSON.stringify(payload, null, 2);
}

/**
 * Validates and restores JSON backup into localStorage.
 * Enforces sanitization and schema verification.
 */
export function restoreFromJsonBackup(jsonString: string): { success: boolean; message: string; count?: number } {
  try {
    const data = JSON.parse(jsonString);

    if (!data || typeof data !== 'object') {
      return { success: false, message: 'Invalid JSON: root must be an object' };
    }

    if (!Array.isArray(data.spaces) || !Array.isArray(data.documents) || !Array.isArray(data.tasks)) {
      return { success: false, message: 'Malformed backup schema: spaces, documents, and tasks arrays required' };
    }

    // Persist verified collections
    localStorage.setItem('whitespace_spaces', JSON.stringify(data.spaces));
    localStorage.setItem('whitespace_documents', JSON.stringify(data.documents));
    localStorage.setItem('whitespace_tasks', JSON.stringify(data.tasks));

    if (Array.isArray(data.members) && data.members.length > 0) {
      localStorage.setItem('whitespace_members', JSON.stringify(data.members));
    }

    if (Array.isArray(data.tabs)) {
      localStorage.setItem('whitespace_browser_tabs', JSON.stringify(data.tabs));
    }

    if (data.chatStore && typeof data.chatStore === 'object') {
      localStorage.setItem('whitespace_chat_store', JSON.stringify(data.chatStore));
    }

    const count = data.spaces.length + data.documents.length + data.tasks.length;
    return {
      success: true,
      message: `RESTORED ${count} WORKSPACE ENTITIES SUCCESSFULLY`,
      count
    };
  } catch (err: any) {
    return { success: false, message: `JSON parsing error: ${err.message}` };
  }
}

/**
 * Generates standalone, dependency-free Python 3 local bridge script `wc_bridge.py`.
 * Enables Google Antigravity, Cursor, and local CLI tools to consume workspace data.
 */
export function generateBridgeScript(spaceName: string): string {
  const lines = [
    '#!/usr/bin/env python3',
    '"""',
    'White Collars (WHITESPACE) // Local Agent Bridge (wc_bridge.py)',
    '----------------------------------------------------------------',
    'Standalone, zero-dependency Python 3 bridge for Google Antigravity,',
    'Cursor, and local CLI agents.',
    '',
    "Synchronizes workspace context packages into a local '.whitespace/'",
    'directory structure ready for direct RAG, code analysis, and agent execution.',
    '',
    'Usage:',
    '    python wc_bridge.py                 # Syncs from context.md in current directory',
    '    python wc_bridge.py <path_to_context.md>',
    '    python wc_bridge.py --init          # Generates empty .whitespace/ scaffold',
    '"""',
    '',
    'import os',
    'import sys',
    'import json',
    'import re',
    'from pathlib import Path',
    '',
    'WORKSPACE_DIR = Path(".whitespace")',
    'DOCS_DIR = WORKSPACE_DIR / "DOCS"',
    '',
    'def log(msg):',
    '    print(f"[WHITE COLLARS BRIDGE] {msg}")',
    '',
    'def init_scaffold():',
    '    WORKSPACE_DIR.mkdir(exist_ok=True)',
    '    DOCS_DIR.mkdir(exist_ok=True)',
    '    soul_file = WORKSPACE_DIR / "SOUL.MD"',
    '    if not soul_file.exists():',
    '        soul_file.write_text("# WHITE COLLARS // SYSTEM PROMPT\\nStrict monochrome. Zero latency. Production discipline.\\n", encoding="utf-8")',
    '    log("Created .whitespace/ scaffold.")',
    '',
    'def parse_and_sync(context_path: Path):',
    '    if not context_path.exists():',
    '        log(f"Error: Context file not found: {context_path}")',
    '        log("Export context.md from White Collars OS via the [EXPORT] button in the TopBar.")',
    '        sys.exit(1)',
    '',
    '    content = context_path.read_text(encoding="utf-8")',
    '    WORKSPACE_DIR.mkdir(exist_ok=True)',
    '    DOCS_DIR.mkdir(exist_ok=True)',
    '',
    '    # 1. Write CONTEXT.md replica',
    '    (WORKSPACE_DIR / "CONTEXT.md").write_text(content, encoding="utf-8")',
    '    log("Synced .whitespace/CONTEXT.md")',
    '',
    '    # 2. Extract SOUL.MD',
    '    soul_match = re.search(r"## 3\\. PERSISTENT SPACE SYSTEM PROMPT \\(SOUL\\.MD\\)\\s+```markdown\\n(.*?)\\n```", content, re.DOTALL)',
    '    if soul_match:',
    '        soul_text = soul_match.group(1).strip()',
    '        (WORKSPACE_DIR / "SOUL.MD").write_text(soul_text + "\\n", encoding="utf-8")',
    '        log("Synced .whitespace/SOUL.MD")',
    '',
    '    # 3. Extract Tasks',
    '    tasks = []',
    '    task_matches = re.finditer(r"#### \\[([^\\]]+)\\] (.*?)\\n- Task ID: `([^`]+)`\\n- Spec: (.*?)(?=\\n\\n|####|###|$)", content, re.DOTALL)',
    '    for m in task_matches:',
    '        priority = m.group(1).strip()',
    '        title = m.group(2).strip()',
    '        tid = m.group(3).strip()',
    '        spec = m.group(4).strip()',
    '        tasks.append({',
    '            "id": tid,',
    '            "title": title,',
    '            "priority": priority,',
    '            "spec": spec',
    '        })',
    '',
    '    (WORKSPACE_DIR / "TASKS.json").write_text(json.dumps(tasks, indent=2), encoding="utf-8")',
    '    log(f"Synced .whitespace/TASKS.json ({len(tasks)} tasks)")',
    '',
    '    # 4. Extract Knowledge Base Documents',
    '    doc_matches = re.finditer(r"### DOCUMENT \\d+: (.*?) \\(\\.(.*?)\\)\\n- \\*\\*ID\\*\\*: `([^`]+)`.*?```(?:\\w+)?\\n(.*?)\\n```", content, re.DOTALL)',
    '    doc_count = 0',
    '    for dm in doc_matches:',
    '        title = dm.group(1).strip().replace("/", "_").replace("\\\\", "_")',
    '        fmt = dm.group(2).strip()',
    '        doc_content = dm.group(4)',
    '        doc_filename = f"{title}.{fmt}"',
    '        (DOCS_DIR / doc_filename).write_text(doc_content, encoding="utf-8")',
    '        doc_count += 1',
    '',
    '    log(f"Synced .whitespace/DOCS/ ({doc_count} documents)")',
    '    log("Status: 100% IN SYNC WITH WHITE COLLARS OS")',
    `    log("Active Space: ${spaceName}")`,
    '    log("Ready for Google Antigravity, Cursor, and local CLI tools.")',
    '',
    'def main():',
    '    if len(sys.argv) > 1 and sys.argv[1] == "--init":',
    '        init_scaffold()',
    '        return',
    '',
    '    target_file = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("context.md")',
    '    if not target_file.exists():',
    '        # Check parent or current directory',
    '        candidates = list(Path(".").glob("*context*.md"))',
    '        if candidates:',
    '            target_file = candidates[0]',
    '',
    '    parse_and_sync(target_file)',
    '',
    'if __name__ == "__main__":',
    '    main()',
    ''
  ];
  return lines.join('\n');
}

/**
 * Triggers browser file download using standard Blob and object URL.
 */
export function triggerFileDownload(filename: string, content: string, mimeType: string = 'text/plain'): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
